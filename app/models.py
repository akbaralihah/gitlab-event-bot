from datetime import datetime

from sqlalchemy import (
    BigInteger,
    Boolean,
    Column,
    DateTime,
    ForeignKey,
    String,
    Table,
    Text,
    func,
    false,
    true,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base

gitlab_users_projects = Table(
    "gitlab_users_projects",
    Base.metadata,
    Column("gitlabuser_id", ForeignKey("gitlab_users.id", ondelete="CASCADE"), primary_key=True),
    Column("gitlabproject_id", ForeignKey("gitlab_projects.id", ondelete="CASCADE"), primary_key=True),
)


class TelegramGroup(Base):
    __tablename__ = "telegram_groups"

    id: Mapped[int] = mapped_column(primary_key=True)
    chat_id: Mapped[int] = mapped_column(BigInteger, unique=True)
    chat_name: Mapped[str] = mapped_column(String(255))
    chat_type: Mapped[str] = mapped_column(String(50))
    username: Mapped[str | None] = mapped_column(String(255))
    description: Mapped[str | None] = mapped_column(Text)
    is_forum: Mapped[bool] = mapped_column(Boolean, default=False, server_default=false())
    message_thread_id: Mapped[int | None] = mapped_column(BigInteger)
    message_thread_name: Mapped[str | None] = mapped_column(String(255))
    is_active: Mapped[bool] = mapped_column(Boolean, default=False, server_default=false())
    registered_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    projects: Mapped[list["GitlabProject"]] = relationship(back_populates="telegram_group")

    def __str__(self) -> str:
        return f"{self.chat_name} ({self.chat_id})"


class GitlabProject(Base):
    __tablename__ = "gitlab_projects"

    id: Mapped[int] = mapped_column(primary_key=True)
    name: Mapped[str] = mapped_column(String(255), unique=True)
    telegram_group_id: Mapped[int | None] = mapped_column(ForeignKey("telegram_groups.id", ondelete="SET NULL"))

    show_user: Mapped[bool] = mapped_column(Boolean, default=True, server_default=true())
    show_project: Mapped[bool] = mapped_column(Boolean, default=True, server_default=true())
    show_branch: Mapped[bool] = mapped_column(Boolean, default=True, server_default=true())
    show_status: Mapped[bool] = mapped_column(Boolean, default=True, server_default=true())
    show_duration: Mapped[bool] = mapped_column(Boolean, default=True, server_default=true())

    telegram_group: Mapped[TelegramGroup | None] = relationship(back_populates="projects")
    users: Mapped[list["GitlabUser"]] = relationship(secondary=gitlab_users_projects, back_populates="projects")
    events: Mapped[list["GitLabEvent"]] = relationship(back_populates="project", cascade="all, delete-orphan")

    def __str__(self) -> str:
        return self.name


class GitlabUser(Base):
    __tablename__ = "gitlab_users"

    id: Mapped[int] = mapped_column(primary_key=True)
    gitlab_id: Mapped[int] = mapped_column(BigInteger, unique=True)
    gitlab_username: Mapped[str | None] = mapped_column(String(255), unique=True)
    telegram_id: Mapped[int] = mapped_column(BigInteger, unique=True)

    projects: Mapped[list[GitlabProject]] = relationship(secondary=gitlab_users_projects, back_populates="users")

    def __str__(self) -> str:
        return self.gitlab_username or str(self.gitlab_id)


class GitLabEvent(Base):
    __tablename__ = "gitlab_events"

    id: Mapped[int] = mapped_column(primary_key=True)
    gitlab_event: Mapped[str] = mapped_column(String(20))  # push | merge | pipeline
    project_id: Mapped[int] = mapped_column(ForeignKey("gitlab_projects.id", ondelete="CASCADE"))
    status: Mapped[str] = mapped_column(String(50))
    branch: Mapped[str] = mapped_column(String(255))
    user_name: Mapped[str | None] = mapped_column(String(255))
    duration: Mapped[int | None] = mapped_column()
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    project: Mapped[GitlabProject] = relationship(back_populates="events")

    def __str__(self) -> str:
        return f"{self.gitlab_event} - {self.project_id} - {self.user_name}"


class TelegramAdmin(Base):
    __tablename__ = "telegram_admins"

    id: Mapped[int] = mapped_column(primary_key=True)
    telegram_id: Mapped[int] = mapped_column(BigInteger, unique=True)
    full_name: Mapped[str] = mapped_column(String(255))
    username: Mapped[str | None] = mapped_column(String(255))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    def __str__(self) -> str:
        return f"{self.full_name} (@{self.username})"


class WebhookSecret(Base):
    """GitLab webhook signing token (`whsec_...`), generated by GitLab and entered in the admin panel."""

    __tablename__ = "webhook_secrets"

    id: Mapped[int] = mapped_column(primary_key=True)
    name: Mapped[str] = mapped_column(String(255), unique=True)
    token: Mapped[str] = mapped_column(String(512))
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, server_default=true())
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    def __str__(self) -> str:
        return self.name
